// Generates src/icons.generated.ts from the CSS package's pixel sprite.
// Run: npm run gen:icons -w @skogai/arcade-react
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const svg = readFileSync(resolve(here, "../../css/src/icons.svg"), "utf8");

const icons = {};
for (const [, id, inner] of svg.matchAll(/<symbol id="sk-([\w-]+)"[^>]*>([\s\S]*?)<\/symbol>/g)) {
  icons[id] = [...inner.matchAll(/<rect x="(\d+)" y="(\d+)" width="(\d+)" height="(\d+)"/g)].map(
    (m) => m.slice(1, 5).map(Number),
  );
}

const names = Object.keys(icons);
const out =
  "// GENERATED by scripts/gen-icons.mjs from packages/css/src/icons.svg. Do not edit.\n" +
  "// Each icon is a list of [x, y, width, height] pixel rects on a 16×16 grid.\n\n" +
  `export const iconNames = ${JSON.stringify(names)} as const;\n\n` +
  "export type IconName = (typeof iconNames)[number];\n\n" +
  "export const iconRects: Record<IconName, readonly (readonly [number, number, number, number])[]> = {\n" +
  names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(icons[n])},`).join("\n") +
  "\n};\n";

writeFileSync(resolve(here, "../src/icons.generated.ts"), out);
console.log(`icons: generated ${names.length} icons`);
